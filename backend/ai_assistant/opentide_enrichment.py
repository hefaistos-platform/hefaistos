# 2. BDR schema generation
# ---------------------------------------------------------------------------

def ai_generate_bdr_schema(
    playbook_data: Dict,
    user_settings,
    force_generate: bool = False,
) -> Optional[Dict]:
    """
    Generate BDR schema fields from user input.

    If ``force_generate`` is False the detection type is first classified; if
    it is THREAT-driven None is returned (BDR not applicable).

    Args:
        playbook_data: All workbench fields dict.
        user_settings: UserAISettings instance.
        force_generate: When True, generate BDR regardless of classification.

    Returns:
        BDR schema dict conforming to ShareTide BDR v2.0, or None.
    """
    if not force_generate:
        classification = ai_classify_detection_type(playbook_data, user_settings)
        if classification != 'BUSINESS':
            return None

    system_prompt = (
        "You are a senior compliance and detection architect. "
        "Return only strict JSON that conforms to the requested schema."
    )
    user_prompt = (
        "Generate a Business-Driven Detection Rule (BDR) schema entry for the detection below.\n\n"
        "Output ONLY a single JSON object with these exact keys (no extra keys, no markdown):\n"
        "{\n"
        '  "criticality": "<one of: Emergency|Severe|High|Medium|Low|Baseline - Negligible|Baseline - Minor>",\n'
        '  "domains": ["<subset of: Enterprise|Public Cloud|Private Cloud|Mobile|SaaS|Networking|'
        'OSINT|Embedded|IoT|Industrial>"],\n'
        '  "targets": ["<relevant asset types>"],\n'
        '  "platforms": ["<relevant platforms from: Windows|Linux|macOS|AWS|Azure|GCP|'
        'Active Directory|Azure AD|Office 365|Network Devices>"],\n'
        '  "violation": "<concise policy or compliance violation description>",\n'
        '  "justification": "<compliance framework and article reference>",\n'
        '  "description": "<clear detection objective statement>"\n'
        "}\n\n"
        f"TITLE: {playbook_data.get('title', '')}\n"
        f"GOAL: {playbook_data.get('goal', '')}\n"
        f"TECHNICAL CONTEXT: {playbook_data.get('technical_context', '')}\n"
        f"COMPLIANCE: {playbook_data.get('compliance', '')}\n\n"
        "Return the JSON object only."
    )

    raw = call_ai_provider(
        '',
        user_settings,
        response_format="json",
        system_prompt=system_prompt,
        user_prompt=user_prompt,
    )
    result = _parse_json_response(raw, {})

    # Apply defaults for any missing required fields
    defaults: Dict[str, Any] = {
        'criticality': 'Medium',
        'domains': [],
        'targets': [],
        'platforms': [],
        'violation': '',
        'justification': '',
        'description': playbook_data.get('goal', ''),
    }
    for key, default in defaults.items():
        if key not in result or not result[key]:
            result[key] = default

    return result


