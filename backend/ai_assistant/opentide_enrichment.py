def ai_enrich_mdr_response(playbook_data: Dict, user_settings) -> Dict:
    """
    Generate comprehensive MDR response procedures for a detection.

    Args:
        playbook_data: All workbench fields, including response_playbook,
            false_positives, default_severity.
        user_settings: UserAISettings instance.

    Returns:
        Enriched response dict conforming to MDR schema v2.1 response section.
    """
    system_prompt = (
        "You are a senior SOC analyst and incident responder. "
        "Return only strict JSON that conforms to the requested schema."
    )
    user_prompt = (
        "Generate a structured response procedure for the detection use-case below.\n\n"
        "Output ONLY a single JSON object (no markdown) with this exact structure:\n"
        "{\n"
        '  "alert_severity": "<one of: Critical|High|Medium|Low|Informational>",\n'
        '  "responders": "<one of: CSIRC|CATCH|MARTI|S1-SA>",\n'
        '  "procedure": {\n'
        '    "analysis": "<step-by-step triage guide for analysts>",\n'
        '    "searches": [\n'
        '      {\n'
        '        "purpose": "<what this search reveals>",\n'
        '        "system": "<one of: Sentinel|Splunk|Elastic|QRadar|Wazuh>",\n'
        '        "query": "<example query string>"\n'
        '      }\n'
        '    ],\n'
        '    "containment": "<incident containment steps>"\n'
        '  }\n'
        "}\n\n"
        f"TITLE: {playbook_data.get('title', '')}\n"
        f"GOAL: {playbook_data.get('goal', '')}\n"
        f"TECHNICAL CONTEXT: {playbook_data.get('technical_context', '')}\n"
        f"SEVERITY: {playbook_data.get('default_severity', 'MEDIUM')}\n"
        f"FALSE POSITIVES: {playbook_data.get('false_positives', '')}\n"
        f"RESPONSE PLAYBOOK: {playbook_data.get('response_playbook', '')}\n\n"
        "Return the JSON object only."
    )

    raw = call_ai_provider(
        '',
        user_settings,
        response_format="json",
        system_prompt=system_prompt,
        user_prompt=user_prompt,
    )
    result = _parse_json_response(raw, {})

    # Ensure required fields with safe defaults
    severity_raw = (result.get('alert_severity') or playbook_data.get('default_severity') or 'Medium')
    # Normalise case: first letter upper
    severity = severity_raw.capitalize() if severity_raw else 'Medium'
    if severity not in _get_vocab('mdr_alert_severities'):
        severity = 'Medium'

    responders = result.get('responders', 'CSIRC')
    mdr_responders = _get_vocab('mdr_responders')
    if responders not in mdr_responders:
        responders = mdr_responders[0] if mdr_responders else 'CSIRC'

    procedure = result.get('procedure') or {}
    if not isinstance(procedure, dict):
        procedure = {}

    return {
        'alert_severity': severity,
        'responders': responders,
        'procedure': {
            'analysis': procedure.get('analysis', ''),
            'searches': procedure.get('searches', []),
            'containment': procedure.get('containment', ''),
        },
    }


