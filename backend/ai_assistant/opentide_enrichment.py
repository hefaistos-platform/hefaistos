def _get_vocab(category: str) -> list:
    """Return vocabulary list for *category* from DB, falling back to constants."""
    try:
        from platform_data.models import ShareTideIndexEntry
        values = list(
            ShareTideIndexEntry.objects
            .filter(category=category)
            .order_by('sort_order', 'value')
            .values_list('value', flat=True)
        )
        if values:
            return values
    except Exception:
        pass
    return _VOCAB_FALLBACKS.get(category, [])


