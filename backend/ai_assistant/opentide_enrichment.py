def _normalize_logsource(value: str) -> Optional[str]:
    """Map a free-form logsource string to a valid DOM schema logsource value.

    Returns the original value unchanged if it is already valid, applies the
    legacy mapping table for old-style names, or returns None when no mapping
    can be found.  Valid logsources are read from the DB (`dom_log_sources`
    category) on each call so that instance-specific entries injected via
    ``Configurations/schema.toml`` are honoured without code changes.
    """
    valid_logsources = _get_dom_log_sources()
    if value in valid_logsources:
        return value
    lower = value.lower()
    for keywords, mapped in _LOGSOURCE_LEGACY_MAP:
        if any(kw in lower for kw in keywords):
            return mapped
    return None


def _normalize_entity(value: str) -> Optional[str]:
    """Map a free-form entity string to a valid DOM schema entity value.

    Accepts both the new ``domain::Entity`` format (e.g. ``host::Process``) and
    legacy plain names (e.g. ``process``).  Returns None when no valid mapping
    exists.
    """
    if value in _DOM_VALID_ENTITIES:
        return value
    # Try plain lowercase lookup (e.g. 'process' → 'host::Process')
    mapped = _ENTITY_SUFFIX_MAP.get(value.lower())
    if mapped:
        return mapped
    # Handle domain::Entity input: split on '::' and try looking up domain+entity
    # then just the entity segment (e.g. 'host::CommandLine' → suffix 'commandline')
    if '::' in value:
        parts = value.split('::', 1)
        # Try 'domain entity' combined
        combined = f"{parts[0].lower()} {parts[1].lower()}"
        mapped = _ENTITY_SUFFIX_MAP.get(combined)
        if mapped:
            return mapped
        # Try just the entity suffix
        suffix = parts[1].lower()
        mapped = _ENTITY_SUFFIX_MAP.get(suffix)
        if mapped:
            return mapped
    return None


def _normalize_methodology(value: str) -> str:
    """Return a valid DOM schema methodology value.

    Accepts the full OpenTide detection method vocabulary.  Falls back to
    'Behavioural' for unrecognised inputs.
    """
    valid = _get_dom_methodologies()
    if value in valid:
        return value
    # Handle common aliases and spelling variants
    aliases: Dict[str, str] = {
        'behavioral': 'Behavioural',
        'behavior': 'Behavioural',
        'correlation': 'Pattern Matching',
        'threshold': 'Statistical',
        'threat intel': 'Threat Intelligence',
        'ml': 'Machine Learning',
    }
    mapped = aliases.get(value.lower())
    if mapped and mapped in valid:
        return mapped
    return 'Behavioural'


def ai_generate_detection_objective(playbook_data: Dict, user_settings) -> Dict:
    """
    Generate Detection Objective Model (DOM) structure including descriptive signals.

    Signals describe WHAT the detection aims to observe (data sources, observable
    behaviour) but do NOT contain any detection query logic — actual detection
    rules (KQL, SPL, Sigma, WAZUH) must always be provided by the user.

    Args:
        playbook_data: All workbench fields dict.
        user_settings: UserAISettings instance.

    Returns:
        DOM schema dict conforming to DOM Schema v2.1.
    """
    valid_logsources = _get_dom_log_sources()
    valid_methodologies = _get_dom_methodologies()
    _logsource_examples = ' | '.join(valid_logsources[:5]) + (' | ...' if len(valid_logsources) > 5 else '')
    _entity_examples = ' | '.join(sorted(_DOM_VALID_ENTITIES))
    _methodology_examples = ' | '.join(sorted(valid_methodologies))

    system_prompt = (
        "You are a senior detection architect. "
        "Return only strict JSON that conforms to the requested DOM schema."
    )
    user_prompt = (
        "Generate a Detection Objective Model (DOM) for the detection use-case below.\n\n"
        "IMPORTANT: Do NOT generate any detection queries or rule logic. "
        "Signals must only contain descriptive metadata about what data sources and "
        "observable behaviours the detection targets.\n\n"
        "STRICT VOCABULARY RULES — you MUST only use values from the lists below. "
        "Do not invent your own values.\n\n"
        f"METHODOLOGY_VOCAB (detection method): {_methodology_examples}\n"
        f"ENTITY_VOCAB (threat surface, domain::Entity format): {_entity_examples}\n"
        f"LOGSOURCE_VOCAB (log sources, tool::name format): {_logsource_examples}\n\n"
        "Output ONLY a single JSON object (no markdown):\n"
        "{\n"
        '  "priority": "<one of: Critical|High|Medium|Low>",\n'
        '  "type": "Threat",\n'
        '  "description": "<clear detection objective statement>",\n'
        '  "false_positives": "<known false positive scenarios or None>",\n'
        '  "composition": "<atomic|composite>",\n'
        '  "signals": [\n'
        '    {\n'
        '      "id": "sig-001",\n'
        '      "name": "<signal name>",\n'
        '      "description": "<what behaviour or event this signal targets>",\n'
        '      "severity": "<one of: Informational|Low|Medium|High|Critical>",\n'
        '      "data": {\n'
        '        "availability": "<one of: Unknown|Not Available|Partial|Complete>",\n'
        '        "requirements": "<technical details of required data>",\n'
        f'        "logsources": ["<one or more values from LOGSOURCE_VOCAB>"]\n'
        '      },\n'
        f'      "methodology": "<one value from METHODOLOGY_VOCAB>",\n'
        f'      "entities": ["<one or more values from ENTITY_VOCAB>"]\n'
        '    }\n'
        '  ]\n'
        "}\n\n"
        f"TITLE: {playbook_data.get('title', '')}\n"
        f"GOAL: {playbook_data.get('goal', '')}\n"
        f"TECHNICAL CONTEXT: {playbook_data.get('technical_context', '')}\n"
        f"MITRE TECHNIQUE: {playbook_data.get('mitre_technique_id', '')} "
        f"{playbook_data.get('mitre_technique_name', '')}\n"
        f"SEVERITY: {playbook_data.get('default_severity', 'MEDIUM')}\n"
        f"FALSE POSITIVES: {playbook_data.get('false_positives', 'None documented')}\n\n"
        "Return the JSON object only. Do not include any query logic or pseudocode in signals."
    )

    raw = call_ai_provider(
        '',
        user_settings,
        response_format="json",
        system_prompt=system_prompt,
        user_prompt=user_prompt,
    )
    result = _parse_json_response(raw, {})

    priority = result.get('priority', 'Medium')
    if priority not in _get_vocab('dom_priorities'):
        priority = 'Medium'

    # Strip any 'logic' field that the AI may have added despite instructions,
    # ensuring detection rule content never comes from AI.
    signals = result.get('signals', []) if isinstance(result.get('signals'), list) else []
    clean_signals = []
    for sig in signals:
        if isinstance(sig, dict):
            # Support both 'data_source' (legacy) and 'data_sources' (list)
            # Extract to variable for use in logsources
            data_source = sig.get('data_source', '')
            if not data_source:
                legacy = sig.get('data_sources', [])
                data_source = legacy[0] if isinstance(legacy, list) and legacy else ''

            # Build logsources array from data_source or existing logsources,
            # then normalise every entry to a schema-compliant tool::name value.
            raw_logsources = list(sig.get('data', {}).get('logsources', []))
            if data_source and data_source not in raw_logsources:
                raw_logsources.insert(0, data_source)
            normalised_logsources: List[str] = []
            for ls in raw_logsources:
                normalised = _normalize_logsource(ls)
                if normalised and normalised not in normalised_logsources:
                    normalised_logsources.append(normalised)

            # Normalise entities to schema-compliant plain names.
            raw_entities = sig.get('entities', [])
            normalised_entities: List[str] = []
            for ent in (raw_entities if isinstance(raw_entities, list) else []):
                normalised_ent = _normalize_entity(ent)
                if normalised_ent and normalised_ent not in normalised_entities:
                    normalised_entities.append(normalised_ent)

            clean_signals.append({
                'uuid': str(uuid.uuid4()),
                'name': sig.get('name', ''),
                'description': sig.get('description', ''),
                'severity': sig.get('severity', 'Medium'),
                'data': {
                    'availability': sig.get('data', {}).get('availability', 'Unknown'),
                    'requirements': sig.get('data', {}).get('requirements', f'Requires {data_source}'),
                    'logsources': normalised_logsources,
                },
                'methodology': _normalize_methodology(sig.get('methodology', 'Behavioural')),
                'entities': normalised_entities,
            })

    return {
        'priority': priority,
        'type': result.get('type', 'Threat'),
        'description': result.get('description', playbook_data.get('goal', '')),
        'false_positives': result.get('false_positives') or playbook_data.get('false_positives') or '',
        'composition': result.get('composition', 'atomic'),
        'signals': clean_signals,
    }
