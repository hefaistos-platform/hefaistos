def ai_classify_detection_type(playbook_data: Dict, user_settings) -> str:
    """
    Classify a detection use-case as THREAT or BUSINESS driven.

    Analyses the title, goal, technical context and any compliance keyword
    signals in the playbook fields.

    Args:
        playbook_data: Dict with keys: title, goal, technical_context, and
            optionally compliance (str).
        user_settings: UserAISettings (or effective settings) instance.

    Returns:
        "THREAT" or "BUSINESS"
    """
    system_prompt = (
        "You are a senior detection engineering architect. "
        "Classify detection use-cases and return only strict JSON."
    )
    user_prompt = (
        "Classify the following detection use-case as either THREAT-driven or BUSINESS-driven.\n\n"
        "THREAT-driven: focuses on adversary techniques, MITRE ATT&CK tactics, malware, threat actors.\n"
        "BUSINESS-driven: focuses on compliance requirements, policy violations, insider risk, "
        "data governance, regulatory obligations (GDPR, PCI-DSS, HIPAA, etc.).\n\n"
        'Output ONLY a JSON object with two keys: "classification" ("THREAT" or "BUSINESS") '
        'and "confidence" (0.0 to 1.0). No other text.\n\n'
        f"TITLE: {playbook_data.get('title', '')}\n"
        f"GOAL: {playbook_data.get('goal', '')}\n"
        f"TECHNICAL CONTEXT: {playbook_data.get('technical_context', '')}\n"
        f"COMPLIANCE: {playbook_data.get('compliance', '')}\n\n"
        "Return the JSON object only."
    )

    raw = call_ai_provider(
        '',
        user_settings,
        response_format="json",
        system_prompt=system_prompt,
        user_prompt=user_prompt,
    )
    result = _parse_json_response(raw, {})
    classification = (result.get('classification') or 'THREAT').upper()
    if classification not in ('THREAT', 'BUSINESS'):
        classification = 'THREAT'
    return classification


